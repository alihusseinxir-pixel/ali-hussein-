export function seedIfEmpty() {
  if (!db.listTenants().length) {
    db.saveTenant(structuredClone(EXAMPLE_RESTAURANT));
    console.log("🌱 انضاف مطعم تجريبي (بيت الكبة) حتى تجرب النظام");
  }
  // نعلم المطعم التجريبي القديم (قبل ما نضيف علامة demo)
  const demo = db.listTenants().find((t) => t.demo) || db.listTenants().find((t) => t.name === EXAMPLE_RESTAURANT.name);
  if (demo && !demo.demo) db.saveTenant({ id: demo.id, demo: true });
  if (!db.listTenants().some((t) => t.role === "sales")) {
    db.saveTenant(structuredClone(SALES_TENANT));
    console.log("🌱 انضاف محل المبيعات (النظام يبيع نفسه)");
  }
}

export const demoTenant = () => db.listTenants().find((t) => t.demo) || null;
export const salesTenant = () => db.listTenants().find((t) => t.role === "sales") || null;
