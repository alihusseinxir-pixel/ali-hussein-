export const prospectBrand = (slug) => PROSPECTS.find((p) => p.slug === slug)?.brand || null;

export const demoTenant = () => db.listTenants().find((t) => t.demo) || null;
export const salesTenant = () => db.listTenants().find((t) => t.role === "sales") || null;
